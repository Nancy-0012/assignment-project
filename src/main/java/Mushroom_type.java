    private void btnidentifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnidentifyActionPerformed
    int forest = 0;
    int convex = 0;
    int ring = 0;
    int gills = 0;

    if (forestyes.isSelected()) {
        forest = 1;
    }
    if (convexyes.isSelected()) {
        convex = 1;
    }
    if (ringyes.isSelected()) {
        ring = 1;
    }
    if (gillsyes.isSelected()) {
        gills = 1;
    }

    if (forest == 0 && convex == 1) {
        results.setText("Your mushroom is Agaric jaunissant");
    }
    else if (forest == 0 && convex == 0) {
        results.setText("Your mushroom is Coprin chevelu");
    }
    else {
        if (forest == 1 && convex == 1) {
            if (ring == 1) {
                results.setText("Your mushroom is Amanite tue-mouche");
            }
            else {
                results.setText("Your mushroom is Pied bleu");
            }
        }
        else {
            if (gills == 1) {
                results.setText("Your mushroom is Girolle");
            }
            else {
                results.setText("Your mushroom is Cepe de Bordeaux");
            }
        }
    }// TODO add your handling code here:
    }//GEN-LAST:event_btnidentifyActionPerformed

